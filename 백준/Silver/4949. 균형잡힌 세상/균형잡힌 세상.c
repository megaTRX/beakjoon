/* ==========================================================================
   [전처리기 설정 구역]
   컴파일러가 번역을 시작하기 전에 미리 처리하는 명령어들입니다.
   ========================================================================== */
#define _CRT_SECURE_NO_WARNINGS // Visual Studio에서 scanf, fgets 등을 쓸 때 발생하는 "보안 경고(에러)"를 무시하라는 명령입니다.
#include <stdio.h>              // 표준 입출력 함수들(printf, fgets 등)을 사용하기 위해 물러옵니다.
#include <string.h>             // 문자열 관련 함수들(strlen, strcmp 등)을 사용하기 위해 불러옵니다.

#define MAX_LEN 102             // 코드에 있는 모든 'MAX_LEN'을 숫자 102로 바꿉니다.
                                // 100글자 입력 + 엔터(\n) + 널문자(\0) = 102칸 확보

/* ==========================================================================
   [전역 변수 선언]
   함수 바깥에 선언하여 어디서든 접근 가능하지만, 여기서는 스택 메모리로 씁니다.
   ========================================================================== */
char stack[MAX_LEN];            // 문자들을 차곡차곡 쌓아둘 '스택'이라는 창고(배열)를 만듭니다.

int main() {
    /* [변수 초기화]
       top: 스택의 가장 윗부분(현재 위치)을 가리키는 화살표. -1은 "아무것도 없음"을 뜻함.
       i: 반복문을 돌 때 사용할 숫자 변수. */
    int top = -1, i;
    
    /* [입력 버퍼]
       사용자가 키보드로 치는 문장을 저장할 배열입니다. */
    char arr[MAX_LEN];

    /* [최초 입력]
       사용자로부터 첫 번째 문장을 입력받습니다.
       stdin: 키보드 입력
       MAX_LEN: 최대 102글자까지만 받아서 메모리 넘침 방지 */
    fgets(arr, MAX_LEN, stdin);

    /* [메인 루프]
       strcmp(arr, ".\n"): 입력된 문장이 온점(.) 하나와 엔터(\n)인지 비교합니다.
       결과가 0이면(같으면) 반복문 종료(False), 0이 아니면(다르면) 계속 실행(True). */
    while (strcmp(arr, ".\n")) {

        /* 문자열 길이만큼 한 글자씩 검사합니다. */
        for (i = 0; i < strlen(arr); i++) {
            
            /* 1. 여는 소괄호 '(' 를 만났을 때 */
            if (arr[i] == '(') {
                stack[++top] = arr[i]; // top을 1칸 올리고(먼저 증가), 그 자리에 '('를 저장 (Push)
            }
            /* 2. 닫는 소괄호 ')' 를 만났을 때 */
            else if (arr[i] == ')') {
                /* [중요 수정] 안전장치 추가!
                   1) top == -1: 스택이 비어있는데 꺼내려고 하면 에러! (예: 입력이 ")"일 때)
                   2) stack[top--] != '(': 꺼낸 녀석이 내 짝궁 '('가 아니면 에러! */
                if (top == -1 || stack[top--] != '(')
                    break; // 짝이 안 맞으므로 for문을 강제로 탈출
            }
            /* 3. 여는 대괄호 '[' 를 만났을 때 */
            else if (arr[i] == '[') {
                stack[++top] = arr[i]; // top을 1칸 올리고, 그 자리에 '['를 저장 (Push)
            }
            /* 4. 닫는 대괄호 ']' 를 만났을 때 */
            else if (arr[i] == ']') {
                /* [중요 수정] 위와 동일한 안전장치
                   스택이 비었거나, 꺼낸 녀석이 내 짝궁 '['가 아니면 탈출 */
                if (top == -1 || stack[top--] != '[')
                    break; // for문 강제 탈출
            }
        }

        /* [결과 판별]
           반복문이 끝난 뒤, 이 문장이 균형잡힌 문장인지 확인합니다. */
        
        // 조건 1: i != strlen(arr) -> 중간에 break를 만나서 강제로 튀어나왔다는 뜻 (실패)
        // 조건 2: top != -1        -> 다 돌았는데 스택에 괄호가 남아있다는 뜻 (예: "(( " 처럼 닫는게 부족함) (실패)
        if (i != strlen(arr) || top != -1)
            printf("no\n"); // 균형이 맞지 않음
        else
            printf("yes\n"); // 끝까지 잘 돌았고, 스택도 깨끗하게 비어있음 (성공)

        /* [다음 단계 준비]
           다음 문장을 검사하기 위해 상태를 초기화합니다. */
        top = -1;                   // 스택 위치를 다시 "비어있음(-1)"으로 되돌림
        fgets(arr, MAX_LEN, stdin); // 새로운 문장을 입력받음 (이게 없으면 무한루프에 빠짐)
    }

    return 0; // 프로그램 정상 종료
}